export function BrandIcon({
  name,
  className,
  style,
}: {
  name: string;
  className?: string;
  style?: React.CSSProperties;
}) {
  const key = name.toLowerCase();
  const path = BRAND_PATHS[key];

  if (path) {
    return (
      <svg viewBox="0 0 24 24" fill="currentColor" aria-hidden style={style} className={cn("size-5", className)}>
        <path d={path} />
      </svg>
    );
  }

  const Icon = LUCIDE_ICONS[name] ?? LinkIcon;
  return <Icon className={cn("size-5", className)} style={style} aria-hidden />;
}
